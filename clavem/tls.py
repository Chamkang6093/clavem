from __future__ import annotations

import ssl
from collections.abc import Mapping


def _validate(identity: str, key: bytes) -> None:
    if not identity or len(identity.encode("utf-8")) > 255 or "\0" in identity:
        raise ValueError("identity must contain 1-255 UTF-8 bytes without NUL")
    if len(key) != 32:
        raise ValueError("key must contain 32 randomly generated bytes")


def _context(protocol: int) -> ssl.SSLContext:
    if not ssl.HAS_PSK:
        raise RuntimeError("this Python/OpenSSL build does not support TLS-PSK")
    context = ssl.SSLContext(protocol)
    context.minimum_version = ssl.TLSVersion.TLSv1_3
    context.maximum_version = ssl.TLSVersion.TLSv1_3
    return context


def client_context(identity: str, key: bytes) -> ssl.SSLContext:
    """Authenticate with an external PSK; do not trust certificate fallback."""
    _validate(identity, key)
    context = _context(ssl.PROTOCOL_TLS_CLIENT)
    context.check_hostname = False
    # A successful external-PSK handshake needs no CA. Certificate fallback
    # must still fail verification rather than authenticate an unrelated peer.
    context.verify_mode = ssl.CERT_REQUIRED
    context.set_psk_client_callback(lambda _hint: (identity, key))
    return context


def server_context(keys: Mapping[str, bytes]) -> ssl.SSLContext:
    """Accept only the supplied identities and their external PSKs."""
    if not keys:
        raise ValueError("at least one identity is required")
    allowed = dict(keys)
    for identity, key in allowed.items():
        _validate(identity, key)
    context = _context(ssl.PROTOCOL_TLS_SERVER)
    context.num_tickets = 0

    def lookup(identity: str | None) -> bytes:
        if identity not in allowed:
            return b""  # Decline unknown PSKs; no certificate fallback is configured.
        return allowed[identity]

    context.set_psk_server_callback(lookup)
    return context
